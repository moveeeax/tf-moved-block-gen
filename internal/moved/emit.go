package moved

import (
	"fmt"
	"strings"
)

const maxCommentAttrs = 6

// RenderHCL writes the proposed moved blocks as Terraform configuration. The
// output carries no timestamp and no map iteration, so the same plan always
// produces the same bytes.
func RenderHCL(res Result) string {
	var b strings.Builder

	if len(res.Moves) == 0 {
		b.WriteString("# tf-moved-block-gen: no moved blocks proposed for this plan.\n")
		if len(res.Unexplained) > 0 {
			fmt.Fprintf(&b, "# %s with no plausible rename partner.\n", plural(len(res.Unexplained), "destroy", "destroys"))
		}
		return b.String()
	}

	b.WriteString("# Generated by tf-moved-block-gen. Review every block before you apply.\n")
	fmt.Fprintf(&b, "# %s proposed", plural(len(res.Moves), "moved block", "moved blocks"))
	if len(res.Unexplained) > 0 {
		fmt.Fprintf(&b, ", %s still unexplained", plural(len(res.Unexplained), "destroy", "destroys"))
	}
	b.WriteString(".\n")

	for _, m := range res.Moves {
		b.WriteString("\n")
		fmt.Fprintf(&b, "# confidence %.2f", m.Confidence)
		if len(m.Matched) > 0 {
			fmt.Fprintf(&b, " | matched: %s", attrList(m.Matched))
		}
		if len(m.Mismatched) > 0 {
			fmt.Fprintf(&b, " | differs: %s", attrList(m.Mismatched))
		}
		b.WriteString("\n")
		b.WriteString("moved {\n")
		fmt.Fprintf(&b, "  from = %s\n", m.From)
		fmt.Fprintf(&b, "  to   = %s\n", m.To)
		b.WriteString("}\n")
	}
	return b.String()
}

// RenderSummary is the human report that goes to stderr: what was paired and,
// more importantly, what was not.
func RenderSummary(res Result) string {
	var b strings.Builder
	fmt.Fprintf(&b, "%s proposed, %s unexplained",
		plural(len(res.Moves), "moved block", "moved blocks"),
		plural(len(res.Unexplained), "destroy", "destroys"))
	if len(res.Replacements) > 0 {
		fmt.Fprintf(&b, ", %s replaced in place", plural(len(res.Replacements), "resource", "resources"))
	}
	b.WriteString("\n")

	for _, m := range res.Moves {
		fmt.Fprintf(&b, "  rename  %s -> %s (%.2f)\n", m.From, m.To, m.Confidence)
	}
	for _, d := range res.Unexplained {
		fmt.Fprintf(&b, "  DESTROY %s (%s)\n", d.Address, d.Reason)
	}
	for _, r := range res.Replacements {
		fmt.Fprintf(&b, "  replace %s\n", r.Address)
	}
	return b.String()
}

func attrList(keys []string) string {
	if len(keys) <= maxCommentAttrs {
		return strings.Join(keys, ", ")
	}
	return fmt.Sprintf("%s, +%d more", strings.Join(keys[:maxCommentAttrs], ", "), len(keys)-maxCommentAttrs)
}

func plural(n int, one, many string) string {
	if n == 1 {
		return fmt.Sprintf("%d %s", n, one)
	}
	return fmt.Sprintf("%d %s", n, many)
}
